//Numeros reales o flotantes

/* En c++ los numeros reales son representados utilizando dos tipos de datos < float > y < double >,
float es utilizado para guardar numeros con punto decimal, por ejemplo:*/

float price = 9.99f;/*La f al final se utiliza para indocar al compilador que este numero deb tratarse
                    como un numero de coma flotante*/

/* double tambien es utlizado para guardar numeros con punto decimal pero este permite un uso mas
preciso y estenso, ya que < float > solo permite usar 7 digitos desimales mientras que < double >
permite el uso de 15 digitos desimales por ejemplo:*/

float pi_float = 3.14f;
double pi_double = 3.14159265359;