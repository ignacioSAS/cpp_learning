// Constantes

/* Las variables tipo constante son aquellas que una ves inicializadas no pueden modificarse,
para declararlas se utiliza la palabra clave < const > seguida del tipo de variable y su nombre
por ejemplo: */

const int maxValue = 100; //en este ejemplo la variable maxValue se inicializa con el valor 100

/* A menera de convecion en c++ las variables constantes se nombran co letras mayusculas
por ejemplo: */

const int VALUE = 100;
const float PI = 3.14;

//Esto facilita distinguir las variables constantes de las variables normales de tu codigo.
